import os
import requests

# API key must be provided via environment variable; no key is bundled with the repo.
API_KEY = os.environ.get("OPENROUTER_API_KEY")
API_URL = "https://openrouter.ai/api/v1/chat/completions"

# Free models are rate-limited upstream without warning, so we try several in
# order and use the first one that answers. All entries are free tier.
MODELS = [
    "minimax/minimax-m2.7:free",
    "google/gemma-4-31b-it:free",
    "google/gemma-4-26b-a4b-it:free",
    "nvidia/nemotron-3-super-120b-a12b:free",
    "minimax/minimax-m3:free",
]

# Free models can take 20s+ to respond, so allow plenty of headroom.
REQUEST_TIMEOUT = 60


def init_deepseek_api():
    """
    Initialize the career recommendation API.
    """
    if API_KEY:
        print(f"Career recommender ready (key ...{API_KEY[-4:]}, {len(MODELS)} models available)")
    else:
        print("Career recommender: no API key configured, recommendations will be unavailable.")


def recommender_careerpath(user_data):
    """
    Ask the model for a career pathway recommendation based on the user's
    profile. Tries each model in MODELS until one responds successfully.
    """
    headers = {
        "Authorization": f"Bearer {API_KEY}",
        "Content-Type": "application/json",
    }

    prompt = f"""
        Based on the following user data, recommend a career pathway:
        - Skills: {user_data.get('skills')}
        - Interests: {user_data.get('interests')}
        - Education: {user_data.get('education')}
        - Experience: {user_data.get('experience')}
    """

    messages = [
        {"role": "system", "content": "You are a career advisor."},
        {"role": "user", "content": prompt},
    ]

    for model in MODELS:
        payload = {"model": model, "messages": messages, "max_tokens": 800}

        try:
            response = requests.post(
                API_URL, headers=headers, json=payload, timeout=REQUEST_TIMEOUT
            )

            # Rate-limited or unavailable upstream, try the next model.
            if response.status_code in (429, 502, 503):
                print(f"{model} unavailable ({response.status_code}), trying next model.")
                continue

            response.raise_for_status()

            choices = response.json().get("choices", [])
            content = choices[0].get("message", {}).get("content", "").strip() if choices else ""

            if content:
                print(f"Recommendation generated by {model}")
                return content

            print(f"{model} returned an empty response, trying next model.")

        except requests.exceptions.RequestException as e:
            print(f"{model} error: {e}")

    return "Failed to fetch career recommendation."
